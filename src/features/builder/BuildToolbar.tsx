/*
 * Shared build export helpers. The builder toolbar itself now lives in BuilderPage (ported from the
 * design mock); these functions are reused by My Builds, the summary page and the builder.
 */
import type { BuildSnapshot, CatalogItem } from '../../contracts';
import { KIND_LABELS, TIERS, TIER_LABELS, kindsInTier } from '../../contracts';
import { evidenceLine } from './evidence';

/** Triggers a client-side file download (no server round trip). */
export function download(name: string, text: string, type = 'application/json') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Keep recorded text literal and within one Markdown table cell. */
function markdownCell(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/[\r\n\u2028\u2029]+/g, ' ')
    .replace(/[\\`*_[\]{}()#!|~$]/g, '\\$&');
}

/** Human-readable Markdown summary of a build (kept alongside the JSON export). */
export function buildMarkdown(
  build: BuildSnapshot,
  byId: ReadonlyMap<string, CatalogItem>,
): string {
  const lines = [
    `# ${build.name}`,
    '',
    `Revision ${build.revision} · contract BuildSnapshot ${build.schema_version} · catalog ${build.locks.catalog_snapshot_id}`,
    `Pricebook: ${build.locks.pricebook_id ?? 'Not specified'}${build.locks.pricebook_id?.startsWith('prices.demo.') ? ' — Synthetic demo pricebook' : ''}`,
    '',
  ];
  for (const tier of TIERS) {
    const rows = kindsInTier(tier).flatMap((k) =>
      build.selections.filter((s) => s.kind === k.kind),
    );
    if (!rows.length) continue;
    lines.push(
      `## ${tier} — ${TIER_LABELS[tier]}`,
      '',
      '| Component | Selection | Role | Enabled | Recorded provenance |',
      '|---|---|---|---|---|',
    );
    for (const s of rows) {
      const candidate = byId.get(s.catalog_item_id);
      // An imported selection may pin another version/kind with the same lookup key.
      const item =
        candidate?.id === s.catalog_item_id &&
        candidate.version === s.catalog_item_version &&
        candidate.kind === s.kind
          ? candidate
          : undefined;
      const name = `${markdownCell(item?.name ?? s.catalog_item_id)}${item?.tags?.includes('synthetic') ? ' (Synthetic)' : ''}`;
      const provenance = item
        ? [
            evidenceLine(item).label,
            ...item.provenance.map((entry) => entry.source_uri).filter(Boolean),
          ].join('; ')
        : 'Record unavailable for selected version or kind';
      lines.push(
        `| ${KIND_LABELS[s.kind]} | ${name} | ${s.role} | ${s.enabled ? 'yes' : 'no'} | ${markdownCell(provenance)} |`,
      );
    }
    lines.push('');
  }
  lines.push(
    '_Generated by PickYour.AI preview. Synthetic records are labelled per selection. Recorded provenance and pricebook estimates are not a quote or independent verification; compatibility checks do not establish production readiness._',
    '',
  );
  return lines.join('\n');
}
