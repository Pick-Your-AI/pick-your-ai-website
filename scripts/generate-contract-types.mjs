#!/usr/bin/env node
// Generates TypeScript types from the vendored contract JSON Schemas (contracts/v1/schemas).
// Output: src/contracts/generated/contract-types.ts — never edit by hand; CI checks it is current.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const SCHEMA_DIR = join(ROOT, 'contracts', 'v1', 'schemas');
const OUT_DIR = join(ROOT, 'src', 'contracts', 'generated');
const ID_BASE = 'https://schemas.ai-builder.example/v1/';

// Exported type name for each top-level schema file.
const ROOTS = {
  'build.schema.json': 'BuildSnapshot',
  'catalog-item.schema.json': 'CatalogItem',
  'catalog-snapshot.schema.json': 'CatalogSnapshot',
  'cost-estimate.schema.json': 'CostEstimate',
  'dependency-graph.schema.json': 'DependencyGraph',
  'deployment-manifest.schema.json': 'DeploymentManifest',
  'evaluation-report.schema.json': 'EvaluationReport',
  'event.schema.json': 'ContractEvent',
  'pricebook.schema.json': 'Pricebook',
  'quality-evaluation-run.schema.json': 'QualityEvaluationRun',
  'resource-estimate.schema.json': 'ResourceEstimate',
  'ruleset.schema.json': 'Ruleset',
  'selection.schema.json': 'Selection',
};

const files = readdirSync(SCHEMA_DIR).filter((f) => f.endsWith('.schema.json'));
for (const f of files) {
  if (f !== 'common.schema.json' && !ROOTS[f]) throw new Error(`No type name configured for ${f}`);
}

const load = (name) => JSON.parse(readFileSync(join(SCHEMA_DIR, name), 'utf8'));

// Resolve the schemas' $id URLs to the vendored files instead of the network.
const localResolver = {
  order: 1,
  canRead: (file) => file.url.startsWith(ID_BASE),
  read: (file) =>
    readFileSync(join(SCHEMA_DIR, file.url.slice(ID_BASE.length).split('#')[0]), 'utf8'),
};

const bundle = {
  $id: `${ID_BASE}__bundle.json`,
  title: 'ContractBundle',
  type: 'object',
  additionalProperties: false,
  properties: {
    ...Object.fromEntries(
      Object.entries(ROOTS).map(([file, name]) => [name, { $ref: `${ID_BASE}${file}` }]),
    ),
    // The envelopes discriminate `spec` / `settings` by kind with if/then, which json-schema-to-typescript
    // cannot express; expose the per-kind variants as lookup maps instead.
    CatalogSpecMap: kindMap('catalog-item.schema.json', 'spec_', 'CatalogSpecMap'),
    SelectionSettingsMap: kindMap('selection.schema.json', 'settings_', 'SelectionSettingsMap'),
  },
};

function kindMap(file, prefix, title) {
  const defs = Object.keys(load(file).$defs).filter((d) => d.startsWith(prefix));
  return {
    title,
    type: 'object',
    additionalProperties: false,
    required: defs.map((d) => d.slice(prefix.length)),
    properties: Object.fromEntries(
      defs.map((d) => [d.slice(prefix.length), { $ref: `${ID_BASE}${file}#/$defs/${d}` }]),
    ),
  };
}

// Give each top-level schema the configured title so its generated interface gets a stable name.
const titled = new Map(
  Object.entries(ROOTS).map(([file, name]) => [file, { ...load(file), title: name }]),
);
const titledResolver = {
  ...localResolver,
  order: 0,
  read: (file) => {
    const name = file.url.slice(ID_BASE.length).split('#')[0];
    return titled.has(name) ? JSON.stringify(titled.get(name)) : localResolver.read(file);
  },
};

let ts = await compile(bundle, 'ContractBundle', {
  bannerComment: `/* eslint-disable */
/**
 * GENERATED by scripts/generate-contract-types.mjs from contracts/v1/schemas — DO NOT EDIT.
 * Source: Pick-Your-AI/pick-your-ai-research contracts/v1 (see contracts/PROVENANCE.json).
 * Regenerate with \`npm run contracts:types\`.
 */`,
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: false,
  strictIndexSignatures: true,
  // minItems is enforced by the validators; tuple types would make ordinary array updates awkward.
  ignoreMinAndMaxItems: true,
  format: false,
  $refOptions: { resolve: { file: false, http: false, contract: titledResolver } },
});

ts = await prettier.format(ts, { parser: 'typescript', singleQuote: true, printWidth: 100 });
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'contract-types.ts'), ts);
console.log(`Wrote src/contracts/generated/contract-types.ts (${ts.split('\n').length} lines).`);

// ---------------------------------------------------------------------------
// Standalone Ajv validators. Compiled ahead of time so the browser never needs `new Function`
// (keeps the CSP free of 'unsafe-eval'). Output: src/contracts/generated/validators.js
// ---------------------------------------------------------------------------
const { default: Ajv2020 } = await import('ajv/dist/2020.js');
const { default: addFormats } = await import('ajv-formats');
const { default: standaloneCode } = await import('ajv/dist/standalone/index.js');

const ajv = new Ajv2020({
  allErrors: false,
  strict: false,
  code: { source: true, esm: true, lines: false, optimize: true },
});
addFormats(ajv);
for (const f of files) ajv.addSchema(load(f));
ajv.addSchema(
  { ...JSON.parse(readFileSync(join(SCHEMA_DIR, 'component-registry.json'), 'utf8')) },
  'component-registry',
);

const exportsMap = Object.fromEntries(
  Object.entries(ROOTS).map(([file, name]) => [`validate${name}`, `${ID_BASE}${file}`]),
);
let js = standaloneCode(ajv, exportsMap);

// Ajv emits CommonJS `require` calls for its runtime helpers even in ESM mode; hoist them to
// namespace imports of the same CommonJS modules. Bundlers differ in how they expose module.exports
// (as the namespace's `default` or merged into the namespace), so `__interop` normalises both.
const header = [];
const modules = new Map();
js = js.replace(/require\("([^"]+)"\)/g, (_, mod) => {
  if (!modules.has(mod)) {
    modules.set(mod, `__cjs${modules.size}`);
    const n = modules.get(mod);
    header.push(`import * as ${n}_ns from '${mod}.js';`, `const ${n} = __interop(${n}_ns);`);
  }
  return modules.get(mod);
});
header.unshift(
  'function __interop(ns) {',
  '  const d = ns && ns.default;',
  "  return d && typeof d === 'object' && ('default' in d || 'fullFormats' in d) ? d : ns;",
  '}',
);
js = `/* eslint-disable */\n// @ts-nocheck\n// GENERATED by scripts/generate-contract-types.mjs from contracts/v1/schemas — DO NOT EDIT.\n${header.join('\n')}\n${js}`;
writeFileSync(join(OUT_DIR, 'validators.js'), js);

const dts = `// GENERATED by scripts/generate-contract-types.mjs — DO NOT EDIT.
export interface ContractValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}
export interface ContractValidateFunction {
  (data: unknown): boolean;
  errors?: ContractValidationError[] | null;
}
${Object.keys(exportsMap)
  .map((n) => `export declare const ${n}: ContractValidateFunction;`)
  .join('\n')}
`;
writeFileSync(join(OUT_DIR, 'validators.d.ts'), dts);
console.log(
  `Wrote src/contracts/generated/validators.js (${Math.round(js.length / 1024)} KiB) and validators.d.ts.`,
);
